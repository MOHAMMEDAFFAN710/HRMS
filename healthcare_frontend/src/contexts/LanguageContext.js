const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState(() => localStorage.getItem("careline-language") || "en");
    const changeLanguage = (nextLanguage) => {
        setLanguage(nextLanguage);
        localStorage.setItem("careline-language", nextLanguage);
    };
    const value = { language, changeLanguage, t: translations[language] || translations.en };
    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);
